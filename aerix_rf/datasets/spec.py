"""Sidecar schema (v1) for canonical dataset windows.

Mirrors ``docs/design/dataset-normalization.md`` section 2 (sidecar schema)
and section 3 (label taxonomy). One ``WindowSidecar`` describes one
``<uid>.json`` next to one ``<uid>.c64.npy`` canonical window (or a
``S6_image``-only entry with no IQ artefact).

All models use ``extra="forbid"``: an unrecognised field is a bug (stale
config, typo, or a field that belongs in a different group), not something to
silently accept.

Design note (ambiguity resolved here, not specified verbatim in the memo):
``manufacturer`` / ``model`` / ``individual_id`` are open-vocabulary dataset
identifiers (airframe/controller names, per-dataset serials), not a bounded
enum -- unlike ``emitter_class`` / ``link_family`` / ``link_role`` /
``activity`` which the memo gives explicit enums for. They are plain strings
defaulting to the literal ``"unknown"`` sentinel rather than an Enum member,
because the label taxonomy table in the memo is itself open-ended (new models
show up per dataset). ``label_source`` and ``Split`` are not given explicit
enumerations in the memo either; the members below are the minimal set the
memo's own text implies (evidence provenance in section 2/3; train/val/test
plus "not yet assigned" for section 4's group-level splitter).
"""

from __future__ import annotations

import math
from enum import Enum
from typing import Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator

# Schema version stays 1: this is a field-optionality/notes fix (adding
# Optional[float]/notes, not a breaking structural change), and the only
# prepared corpus so far (RUB-SysSec, 4 windows) is regenerated by this same
# change -- see aerix_rf.datasets.adapters RubDroneSecurityAdapter.
SCHEMA_VERSION = 1


def _reject_non_finite(v: Optional[float]) -> Optional[float]:
    """Shared validator body: ``None`` (genuinely unknown) is fine, but NaN
    and +/-inf are never legal for a frequency field -- they are not the
    same thing as "unknown" and must not silently enter an offset/arithmetic
    expression downstream."""

    if v is not None and not math.isfinite(v):
        raise ValueError(f"non-finite value not allowed: {v!r}")
    return v


class _Strict(BaseModel):
    """Base model: forbid unknown keys, validate on assignment."""

    model_config = ConfigDict(extra="forbid", validate_assignment=True)


# --------------------------------------------------------------------------
# Label taxonomy enums (section 3). `unknown` (we don't know) and
# `not_applicable` (the axis doesn't apply to this emitter) are always
# distinct members -- never collapsed to one sentinel.
# --------------------------------------------------------------------------


class EmitterClass(str, Enum):
    BACKGROUND = "background"
    WIFI = "wifi"
    BLUETOOTH = "bluetooth"
    OTHER_ISM = "other_ism"
    DRONE_LINK = "drone_link"
    MIXED = "mixed"
    UNKNOWN = "unknown"


class LinkFamily(str, Enum):
    OCUSYNC = "ocusync"
    LIGHTBRIDGE = "lightbridge"
    WIFI_DRONE = "wifi_drone"
    FHSS_RC = "fhss_rc"
    ANALOG_FPV = "analog_fpv"
    UNKNOWN = "unknown"
    NOT_APPLICABLE = "not_applicable"


class LinkRole(str, Enum):
    UPLINK_CONTROL = "uplink_control"
    DOWNLINK_VIDEO = "downlink_video"
    BROADCAST_DRONEID = "broadcast_droneid"
    UNKNOWN = "unknown"
    NOT_APPLICABLE = "not_applicable"


class Activity(str, Enum):
    OFF = "off"
    POWERED_IDLE = "powered_idle"
    CONNECTED_IDLE = "connected_idle"
    HOVERING = "hovering"
    FLYING = "flying"
    FLYING_VIDEO = "flying_video"
    UNKNOWN = "unknown"


class EvidenceLevel(int, Enum):
    """Section "Evidence levels": 1 RF candidate .. 5 operator-provided truth."""

    RF_CANDIDATE = 1
    PROBABILISTIC_CLASSIFICATION = 2
    PROTOCOL_SPECIFIC_EVIDENCE = 3
    VALIDATED_DECODE = 4
    OPERATOR_TRUTH = 5


class LabelSource(str, Enum):
    """Where a `scene`/`window` label instance came from."""

    DATASET_METADATA = "dataset_metadata"
    FILENAME_DERIVED = "filename_derived"
    OPERATOR_GROUND_TRUTH = "operator_ground_truth"
    PROTOCOL_DECODE = "protocol_decode"
    HEURISTIC_INFERENCE = "heuristic_inference"
    IMPUTED = "imputed"
    UNKNOWN = "unknown"


class StageEntry(str, Enum):
    """Pipeline entry point (section 1): how much provenance a window has."""

    S0 = "S0"
    S1 = "S1"
    S2 = "S2"
    S3 = "S3"
    S4 = "S4"
    S5 = "S5"
    S6 = "S6"
    S6_IMAGE = "S6_image"
    S7 = "S7"


class GainMode(str, Enum):
    MANUAL = "manual"
    AGC = "agc"
    UNKNOWN = "unknown"


class Split(str, Enum):
    """Group-level split assignment (section 4). Never assigned per-window."""

    TRAIN = "train"
    VAL = "val"
    TEST = "test"
    UNASSIGNED = "unassigned"


# --------------------------------------------------------------------------
# Nested groups
# --------------------------------------------------------------------------


class Identity(_Strict):
    uid: str
    dataset_id: str
    recording_id: str
    source_file: str
    source_sha256: str
    device_id: str
    run_id: str
    capture_group: Optional[str] = None
    channel_id: Optional[str] = None
    slice_index: Optional[int] = None
    slice_reason: Optional[str] = None


class SignalInfo(_Strict):
    sample_rate_hz: float
    duration_s: float
    n_samples: int
    # Optional: some sources (e.g. RUB-SysSec DroneSecurity) do not publish
    # the capture centre frequency at all. `None` means "genuinely unknown"
    # and must never be defaulted to a plausible-looking value -- consumers
    # that need an absolute RF frequency must handle `None` explicitly.
    center_freq_hz: Optional[float] = None
    bandwidth_hz: float
    usable_bw_hz: float
    band_deficit: bool = False
    short_window: bool = False

    _validate_center_freq_hz = field_validator("center_freq_hz")(_reject_non_finite)


class ResampleStage(_Strict):
    """One ordered stage of `source.resample_chain` (section 6: no relying on
    `resample_poly` defaults -- the filter design is recorded explicitly)."""

    op: str
    up: Optional[int] = None
    down: Optional[int] = None
    mix_hz: Optional[float] = None
    numtaps: Optional[int] = None
    window: Optional[str] = None
    cutoff_hz: Optional[float] = None
    stopband_db: Optional[float] = None


class SourceInfo(_Strict):
    original_rate_hz: float
    original_dtype: str
    # Optional for the same reason as `SignalInfo.center_freq_hz` -- see
    # that field's comment. Never defaulted to a placeholder value.
    original_center_freq_hz: Optional[float] = None
    original_bw_hz: float
    iq_full_scale_source: str
    iq_format_source: str
    resample_chain: list[ResampleStage] = Field(default_factory=list)

    _validate_original_center_freq_hz = field_validator("original_center_freq_hz")(
        _reject_non_finite
    )


class ReceiverDevice(_Strict):
    type: Optional[str] = None
    backend: Optional[str] = None
    firmware: Optional[str] = None
    driver: Optional[str] = None
    antenna: Optional[str] = None


class GainInfo(_Strict):
    mode: GainMode
    db: Optional[float] = None
    stages: Optional[int] = None
    changed_within_window: bool = False


class ClockInfo(_Strict):
    source: Optional[str] = None
    pps_locked: Optional[bool] = None


class ReceiverGroup(_Strict):
    receiver: ReceiverDevice
    gain: GainInfo
    dc_offset_corrected: Optional[bool] = None
    quadrature_corrected: Optional[bool] = None
    clock: ClockInfo


class LevelsGroup(_Strict):
    noise_floor_dbfs: Optional[float] = None
    rssi_dbfs: Optional[float] = None
    occupied_bw_hz: Optional[float] = None
    bw_saturated: bool = False
    calibrated: bool = False


class LabelInstance(_Strict):
    """One `scene` or `window` label (section 3). Same shape for both; the
    evidence level and typical source differ by convention, not by schema."""

    emitter_class: EmitterClass
    link_family: LinkFamily = LinkFamily.UNKNOWN
    link_role: LinkRole = LinkRole.UNKNOWN
    manufacturer: str = "unknown"
    model: str = "unknown"
    individual_id: str = "unknown"
    activity: Activity = Activity.UNKNOWN
    evidence_level: EvidenceLevel
    label_source: LabelSource


class LabelsGroup(_Strict):
    scene: LabelInstance
    window: LabelInstance


class BookkeepingGroup(_Strict):
    stage_entry: StageEntry
    preproc_version: str
    config_sha256: str
    code_version: str
    artifact_sha256: Optional[str] = None
    split: Split = Split.UNASSIGNED
    created_at: str


class WindowSidecar(_Strict):
    """Top-level `<uid>.json` sidecar, schema_version 1."""

    schema_version: int = SCHEMA_VERSION
    identity: Identity
    signal: SignalInfo
    source: SourceInfo
    receiver: ReceiverGroup
    levels: LevelsGroup
    labels: LabelsGroup
    bookkeeping: BookkeepingGroup
    # Free-text provenance note for anything not captured by a structured
    # field -- e.g. explaining why `signal.center_freq_hz` /
    # `source.original_center_freq_hz` are `None` for a given source.
    notes: Optional[str] = None
